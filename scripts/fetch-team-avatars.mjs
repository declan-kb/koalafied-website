#!/usr/bin/env node
/*
  Downloads the FIRST avatar for every alliance partner listed in content.js
  and saves it into assets/img/avatars/<season>/frc<team>.png, then rewrites
  assets/js/team-avatars.js so the Robots page knows which ones exist.

  The Blue Alliance doesn't allow its avatar images to be embedded on other
  sites, and its API needs a key, so the avatars are fetched once here and
  served from this site instead. The key is only used wherever this script
  runs (your computer or GitHub Actions); it never ends up in the website.

  This runs automatically on GitHub whenever content.js changes on main
  (see .github/workflows/team-avatars.yml), using the TBA_KEY repository
  secret. To run it by hand instead (Node 18 or newer):
    TBA_KEY=your_read_key node scripts/fetch-team-avatars.mjs

  Get a free Read API key at https://www.thebluealliance.com/account
*/

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const key = process.env.TBA_KEY || process.argv[2];
if (!key) {
  console.error('Missing API key.\n  TBA_KEY=your_read_key node scripts/fetch-team-avatars.mjs\nGet a free Read API key at https://www.thebluealliance.com/account');
  process.exit(1);
}

// content.js is a plain browser script that sets window.SITE_CONTENT.
const sandbox = { window: {} };
vm.runInNewContext(readFileSync(join(root, 'content.js'), 'utf8'), sandbox);
const content = sandbox.window.SITE_CONTENT;

// Same rules as parseTeam() and eventYear() in assets/js/site.js.
const teamNumber = (entry) => {
  const m = String(entry).match(/^\s*(?:team\s*)?(\d+)/i);
  return m ? Number(m[1]) : null;
};
const eventYear = (name) => {
  const m = String(name || '').match(/\b(20\d{2})\b/);
  return m ? Number(m[1]) : null;
};

// Every (season, team) pair that appears as an alliance partner. FIRST
// avatars only exist from 2018 on.
const wanted = new Map();
for (const bot of content.robots?.items ?? []) {
  for (const ev of [...(bot.official ?? []), ...(bot.offseason ?? [])]) {
    const year = eventYear(ev.event);
    if (!year || year < 2018) continue;
    for (const entry of ev.alliance ?? []) {
      const team = teamNumber(entry);
      if (team) wanted.set(`${year}/${team}`, { year, team });
    }
  }
}

const avatarDir = join(root, 'assets/img/avatars');
const firstSeason = 2018;
const lastSeason = new Date().getFullYear();
const missing = [];
let saved = 0;

// A team's avatar for one season as base64 PNG, or null. Cached, since
// the same team often shows up at several events.
const cache = new Map();
async function avatarFor(team, year) {
  const cacheKey = `${year}/${team}`;
  if (cache.has(cacheKey)) return cache.get(cacheKey);
  const res = await fetch(`https://www.thebluealliance.com/api/v3/team/frc${team}/media/${year}`, {
    headers: { 'X-TBA-Auth-Key': key },
  });
  if (res.status === 401) {
    console.error('The Blue Alliance rejected the API key (401). Check TBA_KEY and try again.');
    process.exit(1);
  }
  const media = res.ok ? await res.json() : [];
  const avatar = media.find((m) => m.type === 'avatar' && m.details?.base64Image);
  const result = avatar ? avatar.details.base64Image : null;
  cache.set(cacheKey, result);
  return result;
}

for (const { year, team } of wanted.values()) {
  // Plenty of teams skip uploading an avatar some seasons, so fall back to
  // their nearest other season: year+1, year-1, year+2, and so on.
  let image = null;
  for (let step = 0; !image && step <= lastSeason - firstSeason; step++) {
    for (const y of step ? [year + step, year - step] : [year]) {
      if (y < firstSeason || y > lastSeason) continue;
      image = await avatarFor(team, y);
      if (image) break;
    }
  }
  if (!image) {
    missing.push(`${team}: no avatar in any season`);
    continue;
  }
  mkdirSync(join(avatarDir, String(year)), { recursive: true });
  writeFileSync(join(avatarDir, String(year), `frc${team}.png`), Buffer.from(image, 'base64'));
  saved++;
}

// List every avatar on disk, including ones saved by earlier runs, so the
// site only ever asks for images that exist.
const manifest = {};
if (existsSync(avatarDir)) {
  for (const year of readdirSync(avatarDir).filter((d) => /^\d{4}$/.test(d)).sort()) {
    manifest[year] = readdirSync(join(avatarDir, year))
      .map((file) => file.match(/^frc(\d+)\.png$/))
      .filter(Boolean)
      .map((m) => Number(m[1]))
      .sort((a, b) => a - b);
  }
}
writeFileSync(
  join(root, 'assets/js/team-avatars.js'),
  "// Generated by scripts/fetch-team-avatars.mjs, don't edit by hand.\n" +
  '// Lists which alliance partner avatars are saved in assets/img/avatars/,\n' +
  '// by season.\n' +
  `window.TEAM_AVATARS = ${JSON.stringify(manifest, null, 2)};\n`
);

console.log(`Saved ${saved} of ${wanted.size} avatars.`);
if (missing.length) {
  console.log(`\nThese partners show their initials instead:\n  ${[...new Set(missing)].join('\n  ')}`);
}
